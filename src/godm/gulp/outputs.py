from pathlib import Path
from math import isfinite
from ..models import Atom, GulpOutput, Position
from ..helpers import normalise_core_shell


def read_output(path: Path) -> GulpOutput:
    """Read a GULP output file and parse the completion status, return a GulpOutput object"""
    result = {}
    with path.open(mode="r") as f:
        content = f.readlines()
    atoms = []
    in_atoms = False
    atoms_begins = False
    in_cell = False
    cell_val = {}
    cell_names = ("a", "b", "c", "alpha", "beta", "gamma")
    for line in content:
        tokens = line.split()
        if not tokens:
            continue
        if tokens[:3] == ["Final", "cell", "parameters"]:
            in_cell = True
        if tokens[:2] == ["Job", "Finished"]:
            result["finished"] = True
        if tokens[:2] == ["Final", "Gnorm"]:
            result["lattice_gnorm"] = float(tokens[-1])
        if tokens[:2] == ["Final", "energy"]:
            try:
                energy = float(tokens[-2])
            except ValueError:
                result["has_bad_energy"] = True
                result["lattice_energy"] = None
            else:
                if isfinite(energy):
                    result["lattice_energy"] = energy
                else:
                    result["has_bad_energy"] = True
                    result["lattice_energy"] = None
        if tokens[:3] == ["Final", "fractional", "coordinates"]:
            in_atoms = True
            atoms_begins = False
        if in_cell:
            if tokens[0] in cell_names:
                cell_val[tokens[0]] = float(tokens[1])
                if len(cell_val) == 6:
                    result["cell"] = (
                        cell_val["a"],
                        cell_val["b"],
                        cell_val["c"],
                        cell_val["alpha"],
                        cell_val["beta"],
                        cell_val["gamma"],
                    )
                    in_cell = False
            continue
        if in_atoms:
            if tokens[0].startswith("----"):
                if atoms_begins:
                    in_atoms = False
                continue
            if not tokens[0].isdigit():
                continue
            atoms_begins = True
            x, y, z = map(float, tokens[3:6])
            atom = Atom(
                label=tokens[1],
                kind=normalise_core_shell(tokens[2]),
                position=(x, y, z),
            )

            atoms.append(atom)

            continue
        if tokens[:3] == ["Total", "CPU", "time"]:
            result["cpu_time"] = float(tokens[-1])

    result["atoms"] = atoms
    return GulpOutput(**result)


def read_restart(path: Path) -> tuple[list[Atom], Position]:
    """Read the restart file generated by the dummy defect calculation to obtain the Mott-Littleton Region I"""
    with path.open(mode="r") as f:
        content = f.readlines()
        in_atoms = False
        atoms = []
    for line in content:
        tokens = line.split()
        if not tokens:
            continue
        if tokens[:2] == ["centre", "cart"]:
            centre = (float(tokens[-3]), float(tokens[-2]), float(tokens[-1]))

        if tokens[0] == "region_1":
            in_atoms = True
            continue
        if in_atoms:
            if len(tokens) != 10:
                continue
            else:
                label, kind = tokens[0], normalise_core_shell(tokens[1])
                x, y, z = map(float, tokens[2:5])
                charge = float(tokens[5])
                a = Atom(label=label, kind=kind, position=(x, y, z), charge=charge)
                atoms.append(a)

    return atoms, centre
